#!/usr/bin/env python3
"""Generate the Netlify _redirects map from legacy WordPress URLs to Hugo URLs.

Scans every migrated post/page under content/ for wp_id, date, and slug, then
produces static/_redirects entries covering the main legacy URL shapes:

  WordPress  /YYYY/MM/DD/<slug>/            → Hugo  /<slug>/
  WordPress  /YYYY/MM/DD/<slug>/<anything>/ → Hugo  /<slug>/  (child attachment pages)
  WordPress  /?p=<wp_id>                   → Hugo  /<slug>/
  WordPress  /category/<name>/              → Hugo  /categories/<name>/
  WordPress  /tag/<name>/                   → Hugo  /tags/<name>/
  WordPress  /sobre-mim/                    → Hugo  /sobre/
  WordPress  /en/about-me/                  → Hugo  /en/about/
  WordPress  /wp-content/uploads/           → Hugo  /images/   (legacy image refs)

Netlify _redirects syntax:
  from  to  status

Status codes used:
  301  permanent redirect (most link-equity preserving for SEO)

Writes to static/_redirects.

Idempotent: regenerating with the same inputs produces byte-identical output.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Iterator

import yaml

REPO = Path(__file__).resolve().parent.parent
POST_DIRS = {
    "pt-br": REPO / "content" / "pt-br" / "posts",
    "en": REPO / "content" / "en" / "posts",
}
OUT = REPO / "static" / "_redirects"

# Static WP → Hugo page-slug mapping (manual, for non-post pages).
# WP URL path  →  Hugo URL path
PAGE_REDIRECTS = {
    "/sobre-mim/": "/sobre/",
    "/sobre/": "/sobre/",  # already correct, but add for safety
    "/en/about-me/": "/en/about/",
    "/en/about/": "/en/about/",
    "/recomendacoes/": "/recomendacoes/",
    "/en/recommendations/": "/en/recommendations/",
    # Popular posts (WP original pages 226 / 237)
    "/popular-posts/": "/en/popular-posts/",
    # Recomendações sub-pages that changed slug
    "/recomendacoes/artigos-tech/": "/recomendacoes/artigos-tech/",
    "/recomendacoes/kitesurf/": "/recomendacoes/kitesurf/",
    "/recomendacoes/cafes/": "/recomendacoes/cafes/",
    "/recomendacoes/livros/": "/recomendacoes/livros/",
    "/recomendacoes/arte-em-sp/": "/recomendacoes/arte-em-sp/",
    "/recomendacoes/musica/": "/recomendacoes/musica/",
    "/recomendacoes/viagem-pra-belem/": "/recomendacoes/viagem-pra-belem/",
}


def parse_front_matter(md_path: Path) -> dict | None:
    text = md_path.read_text(encoding="utf-8")
    match = re.match(r"^---\s*\n(.+?)\n---", text, re.DOTALL)
    if not match:
        return None
    try:
        return yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError:
        return None


def iter_posts() -> Iterator[tuple[str, dict]]:
    """Yield (lang, front-matter dict) for every post."""
    for lang, root in POST_DIRS.items():
        for md in root.rglob("index.md"):
            fm = parse_front_matter(md)
            if fm:
                yield lang, fm


def date_parts(date_str: str) -> tuple[str, str, str] | None:
    """Extract YYYY, MM, DD from an ISO date string in front-matter."""
    if not date_str:
        return None
    match = re.match(r"(\d{4})-(\d{2})-(\d{2})", str(date_str))
    if not match:
        return None
    return match.group(1), match.group(2), match.group(3)


def hugo_url(lang: str, slug: str) -> str:
    prefix = "/en" if lang == "en" else ""
    return f"{prefix}/{slug}/"


def generate() -> list[str]:
    lines: list[str] = []
    lines.append("# Generated by scripts/generate_redirects.py — do not edit by hand.")
    lines.append("# Rerun after adding/renaming posts to refresh the map.")
    lines.append("")
    lines.append("# --- Post permalinks: /YYYY/MM/DD/<slug>/ → /<slug>/ ---")

    wp_id_lookup: dict[int, str] = {}  # wp_id → hugo URL

    for lang, fm in iter_posts():
        slug = fm.get("slug")
        if not slug:
            continue
        dp = date_parts(fm.get("date"))
        wp_id = fm.get("wp_id")
        target = hugo_url(lang, slug)

        if dp:
            y, m, d = dp
            # Dated post URL → flat permalink
            lines.append(f"/{y}/{m}/{d}/{slug}/  {target}  301")
            # Child attachment pages (WordPress nested attachments)
            lines.append(f"/{y}/{m}/{d}/{slug}/*  {target}  301")

        if wp_id and isinstance(wp_id, int):
            wp_id_lookup[wp_id] = target

    # Legacy ?p=<wp_id> short URLs
    # Netlify Query matcher uses '=' between key and value, not ':'.
    # Reference: https://docs.netlify.com/routing/redirects/redirect-options/#query-parameters
    lines.append("")
    lines.append("# --- Legacy ?p=<wp_id> short URLs ---")
    for wp_id, target in sorted(wp_id_lookup.items()):
        lines.append(f"/*  {target}  301!  Query=p={wp_id}")

    # Categories and tags (WP → Hugo differ in path name)
    lines.append("")
    lines.append("# --- Category archives: /category/X/ → /categories/X/ ---")
    lines.append("/category/*  /categories/:splat  301")

    lines.append("")
    lines.append("# --- Tag archives: /tag/X/ → /tags/X/ ---")
    lines.append("/tag/*  /tags/:splat  301")

    # Static page redirects
    lines.append("")
    lines.append("# --- Static pages (slug differences) ---")
    for wp, hugo in PAGE_REDIRECTS.items():
        if wp != hugo:
            lines.append(f"{wp}  {hugo}  301")

    # WP media uploads → R2 CDN
    lines.append("")
    lines.append("# --- WP-era /wp-content/uploads/YYYY/MM/<file> → R2 CDN /YYYY/MM/<file> ---")
    lines.append("/wp-content/uploads/*  https://pub-51dee957ac3e4a038150048d60e57b9c.r2.dev/:splat  301")

    # English-locale alternative paths (WP /en/)
    lines.append("")
    lines.append("# --- English alternative paths (WP had /en/YYYY/MM/DD/slug/, same flat for us) ---")
    # Already handled in the post loop above because EN posts are yielded with lang=en.

    lines.append("")
    return lines


def main() -> int:
    lines = generate()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    # Report counts
    post_rules = sum(1 for line in lines if "/20" in line and "/*" not in line)
    print(f"Wrote {OUT.relative_to(REPO)} with {len(lines)} lines")
    print(f"Post date-permalink rules: {post_rules}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
